export function pickLang(request: Request): Lang {
  const url = new URL(request.url);
  const forced = url.searchParams.get("lang");
  if (forced === "es" || forced === "en") {
    return forced;
  }
  return (request.headers.get("accept-language") ?? "").toLowerCase().startsWith("es") ? "es" : "en";
}

function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (m, key: string) => values[key] ?? m);
}

function head(lang: Lang, title: string, description: string): string {
  return (
    `<!doctype html><html lang="${lang}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">` +
    `<title>${escapeHtml(title)} · DustPlanner</title><meta name="description" content="${escapeHtml(description)}"><meta name="robots" content="noindex">` +
    `<meta property="og:title" content="${escapeHtml(title)}"><meta property="og:description" content="${escapeHtml(description)}">` +
    `<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Ccircle cx='16' cy='16' r='13' fill='%23a98cff'/%3E%3C/svg%3E"><style>${STYLE}</style></head><body><main>` +
    `<a class="brand" href="https://dustplanner.app"><span class="mark"></span>DustPlanner</a>`
  );
}

function footer(lang: Lang): string {
  return `<footer>${escapeHtml(TEXT[lang].footer)}</footer></main></body></html>`;
}

export function renderNoDeckPage(lang: Lang, slug: string): string {
  const t = TEXT[lang];
  return (
    head(lang, t.noDeck, t.noDeckBody) +
    `<div class="empty"><h1>${escapeHtml(t.noDeck)}</h1><p>${escapeHtml(t.noDeckBody)}</p><p><a href="https://kick.com/${encodeURIComponent(slug)}">kick.com/${escapeHtml(slug)}</a></p></div>` +
    footer(lang)
  );
}

export function renderDeckPage(lang: Lang, data: DeckPageData, version: string): string {
  const t = TEXT[lang];
  const channel = data.channel.username || data.channel.slug;
  const title = fill(t.title, { channel });
  const description = fill(t.description, { channel });
  const className = data.deck.card_class ? (CLASS_NAMES[lang][data.deck.card_class.toUpperCase()] ?? data.deck.card_class) : null;
  const formatName = data.deck.format ? (FORMAT_NAMES[lang][data.deck.format.toLowerCase()] ?? data.deck.format) : null;
  const meta = [className, formatName].filter((x): x is string => Boolean(x)).map(escapeHtml).join(" · ");
  // Inside a <script> block only "<" can do harm (closing the tag); the two line separators break old JSON parsers.
  const embedded = JSON.stringify({ lang, ...data }).replace(/</g, "\\u003c").replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
  return (
    head(lang, title, description) +
    `<h1>${escapeHtml(data.deck.name)}</h1>` +
    `<p class="meta"><span><a href="https://kick.com/${encodeURIComponent(data.channel.slug)}" rel="noopener">@${escapeHtml(data.channel.slug)}</a> ${escapeHtml(t.by)}</span>${meta ? `<span>${meta}</span>` : ""}<span id="updated"></span></p>` +
    `<div class="actions"><button id="copy" type="button">${escapeHtml(t.copy)}</button><span id="status" aria-live="polite"></span></div>` +
    `<noscript><p>${escapeHtml(t.noScript)}</p></noscript>` +
    `<ul id="cards" aria-label="${escapeHtml(t.code)}"></ul>` +
    `<details open><summary>${escapeHtml(t.code)}</summary><code id="code">${escapeHtml(data.deck.deckstring)}</code></details>` +
    `<script type="application/json" id="deck-data">${embedded}</script>` +
    `<script src="/d/_/deck-page.js?v=${encodeURIComponent(version)}" defer></script>` +
    footer(lang)
  );
}
