import { describe, expect, it } from "vitest";
import { InvalidDeckstringError, decodeDeckstring } from "../client/deckstring";
import fixtures from "./fixtures/deckstrings.json";

interface Vector {
  name: string;
  deckstring: string;
  format: number;
  heroes: number[];
  cards: [number, number][];
  sideboards: [number, number, number][];
}

interface Invalid {
  name: string;
  deckstring: string;
  reason: string;
}

const { vectors, invalid } = fixtures as unknown as { vectors: Vector[]; invalid: Invalid[] };

describe("the browser deckstring decoder (same vectors as the C# codec, generated by python-hearthstone)", () => {
  it.each(vectors.map((v) => [v.name, v] as const))("decodes %s", (_name, vector) => {
    const deck = decodeDeckstring(vector.deckstring);
    expect(deck.format).toBe(vector.format);
    expect(deck.heroes).toEqual(vector.heroes);
    expect(deck.cards.map((c) => [c.dbfId, c.count])).toEqual(vector.cards);
    expect(deck.sideboards.map((s) => [s.dbfId, s.count, s.ownerDbfId])).toEqual(vector.sideboards);
  });

  it.each(invalid.map((v) => [v.name, v] as const))("rejects %s", (_name, bad) => {
    expect(() => decodeDeckstring(bad.deckstring)).toThrow(InvalidDeckstringError);
  });

  it("tolerates surrounding whitespace, like the game's paste box", () => {
    const vector = vectors[0]!;
    expect(decodeDeckstring(`  ${vector.deckstring}\n`).cards.length).toBe(vector.cards.length);
  });
});
